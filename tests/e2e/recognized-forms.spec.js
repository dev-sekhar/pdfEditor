import {test,expect} from '@playwright/test';
import {createRequire} from 'node:module';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
const {PDFDocument,rgb}=createRequire(import.meta.url)('pdf-lib');
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('pdf-studio-release-seen','0.12.0'));await page.goto('/');});
async function download(page){const waiting=page.waitForEvent('download');await page.getByRole('button',{name:'Save PDF',exact:true}).click();const bytes=await readFile(await(await waiting).path());if(process.env.PDF_EDITOR_LOCAL_OUTPUTS){await mkdir(process.env.PDF_EDITOR_LOCAL_OUTPUTS,{recursive:true});await writeFile(path.join(process.env.PDF_EDITOR_LOCAL_OUTPUTS,'recognized-questionnaire-test.pdf'),bytes);}return PDFDocument.load(bytes);}
test('recognizes blank boxes, reviews candidates, types directly and saves real AcroForm values',async({page})=>{
  const doc=await PDFDocument.create(),p=doc.addPage([400,500]);
  p.drawRectangle({x:40,y:400,width:150,height:22,borderWidth:1,borderColor:rgb(0,0,0),color:rgb(1,1,1)});
  p.drawRectangle({x:40,y:350,width:10,height:10,borderWidth:1,borderColor:rgb(0,0,0),color:rgb(1,1,1)});
  for(let i=0;i<6;i++)p.drawRectangle({x:40+i*10,y:300,width:10,height:10,borderWidth:1,borderColor:rgb(0,0,0),color:rgb(1,1,1)});
  await page.getByLabel('Open or merge PDFs').setInputFiles({name:'synthetic-recognition.pdf',mimeType:'application/pdf',buffer:Buffer.from(await doc.save())});
  await expect(page.locator('[aria-label="Selected page"] canvas')).toBeVisible();
  await page.getByRole('button',{name:'Recognize form fields',exact:true}).click();
  await expect(page.getByLabel('Review recognized fields')).toBeVisible();
  expect(await page.locator('.recognized-field').count()).toBeGreaterThanOrEqual(3);
  await page.getByRole('button',{name:/Create \d+ interactive fields/}).click();
  const texts=page.locator('.native-pdf-field[type=text]'),checks=page.locator('.native-pdf-field[type=checkbox]');
  await expect(texts).toHaveCount(2);await expect(checks).toHaveCount(1);
  await texts.nth(0).fill('SYNTHETIC PATIENT');await texts.nth(0).press('Tab');await expect(checks).toBeFocused();
  await checks.check();await texts.nth(1).fill('123456');
  await expect(page.locator('.document-status')).toHaveText('Unsaved changes');
  const saved=await download(page),fields=saved.getForm().getFields();
  expect(fields).toHaveLength(3);
  expect(fields.filter(f=>f.constructor.name==='PDFTextField').map(f=>f.getText())).toEqual(['SYNTHETIC PATIENT','123456']);
  expect(fields.find(f=>f.constructor.name==='PDFCheckBox').isChecked()).toBe(true);
  await expect(texts.nth(0)).toHaveValue('SYNTHETIC PATIENT');
});
test('existing interactive fields allow direct typing, checkbox clicks, undo and save without Apply',async({page})=>{
  const doc=await PDFDocument.create(),p=doc.addPage([400,500]),form=doc.getForm();
  form.createTextField('name').addToPage(p,{x:30,y:400,width:180,height:24});
  form.createCheckBox('confirm').addToPage(p,{x:30,y:350,width:12,height:12});
  await page.getByLabel('Open or merge PDFs').setInputFiles({name:'interactive.pdf',mimeType:'application/pdf',buffer:Buffer.from(await doc.save())});
  const name=page.locator('.native-pdf-field[data-field-name=name]');await name.fill('Alex');
  await page.getByRole('button',{name:'Undo form entry',exact:true}).click();await expect(name).toHaveValue('');
  await page.getByRole('button',{name:'Redo form entry',exact:true}).click();await expect(name).toHaveValue('Alex');
  await page.locator('.native-pdf-field[data-field-name=confirm]').check();
  const saved=await download(page);expect(saved.getForm().getTextField('name').getText()).toBe('Alex');expect(saved.getForm().getCheckBox('confirm').isChecked()).toBe(true);
});
test('local questionnaire recognizes real fields and preserves them after save',async({page})=>{
  test.setTimeout(90000);
  test.skip(!process.env.PDF_EDITOR_PRINTED_FORM,'Optional local acceptance only; user documents are never uploaded.');
  await page.getByLabel('Open or merge PDFs').setInputFiles(process.env.PDF_EDITOR_PRINTED_FORM);
  await expect(page.locator('[aria-label="Selected page"] canvas')).toBeVisible({timeout:20000});
  await page.getByRole('button',{name:'Recognize form fields',exact:true}).click();
  await expect(page.getByLabel('Review recognized fields')).toBeVisible();
  const count=await page.locator('.recognized-field').count();console.log('Local proposals:',count);expect(count).toBeGreaterThan(20);
  await page.screenshot({path:'test-results/local-field-recognition.png',fullPage:true});
  await page.getByRole('button',{name:/Create \d+ interactive fields/}).click();
  const texts=page.locator('.native-pdf-field[type=text]'),checks=page.locator('.native-pdf-field[type=checkbox]');
  await expect(texts.first()).toBeVisible({timeout:20000});await texts.first().fill('1234567890');await checks.first().check();
  await page.getByRole('button',{name:'Select page 2',exact:true}).click();
  await expect(page.locator('[aria-label="Selected page"] canvas')).toBeVisible({timeout:20000});
  await page.getByRole('button',{name:'Fill form',exact:true}).click();
  await expect(page.getByLabel('Review recognized fields')).toBeVisible({timeout:20000});
  const second=await page.locator('.recognized-field').count();expect(second).toBeGreaterThan(0);
  await page.getByRole('button',{name:/Create \d+ interactive fields/}).click();
  await expect(texts.first()).toBeVisible({timeout:20000});await texts.first().fill('1111');
  const saved=await download(page);expect(saved.getForm().getFields().length).toBe(count+second);expect(saved.getForm().getFields().some(f=>f.getText?.()==='1234567890')).toBe(true);
  await expect(texts.first()).toHaveValue('1111',{timeout:20000});
  await page.screenshot({path:'test-results/local-native-fields.png',fullPage:true});
});
