import { test, expect } from '@playwright/test';
import { createRequire } from 'node:module';
const { PDFDocument } = createRequire(import.meta.url)('pdf-lib');

test('click placement, drag, keyboard positioning and history survive zoom and rotation', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('pdf-studio-release-seen', '0.9.0'));
  await page.goto('/');
  const pdf = await PDFDocument.create(); pdf.addPage([600, 800]);
  await page.getByLabel('Open or merge PDFs').setInputFiles({ name: 'blank.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await pdf.save()) });
  await page.getByLabel('Text to add').fill('Move me');
  await page.getByRole('button', { name: 'Place text', exact: true }).click();
  await page.getByLabel('Text overlay placement').click({ position: { x: 80, y: 100 } });
  const handle = page.getByRole('button', { name: 'Move text: Move me' });
  await expect(handle).toBeVisible();
  const before = await handle.boundingBox();
  await page.mouse.move(before.x + before.width / 2, before.y + before.height / 2);
  await page.mouse.down(); await page.mouse.move(before.x + before.width / 2 + 50, before.y + before.height / 2 + 40); await page.mouse.up();
  await expect(page.getByRole('button', { name: 'Undo Move text' })).toBeEnabled();
  await expect(handle).toBeVisible();
  const after = await handle.boundingBox();
  expect(after.x - before.x).toBeCloseTo(50, 0);
  expect(after.y - before.y).toBeCloseTo(40, 0);
  await page.getByRole('button', { name: 'Undo Move text' }).click();
  await expect(handle).toBeVisible();
  expect((await handle.boundingBox()).x).toBeCloseTo(before.x, 0);
  await page.getByRole('button', { name: 'Redo Move text' }).click();
  await expect(handle).toBeVisible();
  await page.getByLabel('Zoom level').selectOption('100');
  await expect(handle).toBeVisible();
  await page.getByRole('button', { name: 'Rotate' }).click();
  await expect(page.locator('.app')).toHaveAttribute('aria-busy', 'false');
  await expect(handle).toBeVisible();
  const rotatedPosition = await handle.boundingBox();
  await handle.focus(); await page.keyboard.press('ArrowRight');
  await expect(page.locator('.app')).toHaveAttribute('aria-busy', 'false');
  await expect(page.getByRole('button', { name: 'Undo Move text' })).toBeEnabled();
  await expect(handle).toBeVisible();
  expect((await handle.boundingBox()).x - rotatedPosition.x).toBeCloseTo(1, 0);
});
